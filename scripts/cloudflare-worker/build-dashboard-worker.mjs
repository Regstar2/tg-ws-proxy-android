import { readFile, writeFile } from "node:fs/promises";

function buildBundle(sources) {
  function replaceOnce(source, from, to) {
    if (source.split(from).length !== 2) throw new Error("Unexpected module structure: " + from);
    return source.replace(from, to);
  }
  function scope(name, source, exposed) {
    if (/^(?:import|export)\b/m.test(source)) throw new Error("Unhandled module declaration in " + name);
    return "const " + name + " = (() => {\n" + source.trimEnd() + "\nreturn { " + exposed + " };\n})();\n";
  }
  function defaultExport(source) {
    return replaceOnce(source, "export default ", "const defaultWorker = ");
  }
  let base = replaceOnce(sources["worker.js"], 'import { connect } from "cloudflare:sockets";\n', "");
  base = defaultExport(replaceOnce(base, "export function createWorkerHandler", "function createWorkerHandler"));
  let relay = replaceOnce(sources["chunk-relay-worker.js"], 'import baseWorker from "./worker.js";', "const baseWorker = __base.defaultWorker;");
  relay = replaceOnce(relay, 'import { connect } from "cloudflare:sockets";\n', "");
  relay = replaceOnce(relay, 'import { DurableObject } from "cloudflare:workers";\n', "");
  relay = replaceOnce(relay, "export class ChunkRelayHub", "class ChunkRelayHub");
  relay = replaceOnce(relay, "export { ChunkRelayHub as ChunkRelaySession };", "");
  relay = defaultExport(relay);
  let status = replaceOnce(sources["chunk-relay-status-worker.js"], 'import chunkRelayWorker, { ChunkRelayHub } from "./chunk-relay-worker.js";', "const { defaultWorker: chunkRelayWorker, ChunkRelayHub } = __relay;");
  status = replaceOnce(status, "export class ChunkRelaySession", "class ChunkRelaySession");
  status = replaceOnce(status, "export { ChunkRelaySession as ChunkRelayHub };", "");
  status = defaultExport(status);
  let bootstrap = replaceOnce(sources["warp-bootstrap-standalone-worker.js"], "export function isWarpBootstrapPath", "function isWarpBootstrapPath");
  bootstrap = replaceOnce(bootstrap, "export async function handleWarpBootstrapRequest", "async function handleWarpBootstrapRequest");
  bootstrap = defaultExport(bootstrap);
  let entry = replaceOnce(sources["warp-bootstrap-worker.js"], 'import relayWorker, { ChunkRelaySession } from "./chunk-relay-status-worker.js";', "const { defaultWorker: relayWorker, ChunkRelaySession } = __status;");
  entry = replaceOnce(entry, 'import {\n  handleWarpBootstrapRequest,\n  isWarpBootstrapPath,\n} from "./warp-bootstrap-standalone-worker.js";', "const { handleWarpBootstrapRequest, isWarpBootstrapPath } = __bootstrap;");
  if (/^import\b/m.test(entry)) throw new Error("Unhandled entry import");
  return "// Generated by build-dashboard-worker.mjs. Do not edit; regenerate from the five source modules.\n" +
    'import { connect } from "cloudflare:sockets";\nimport { DurableObject } from "cloudflare:workers";\n\n' +
    scope("__base", base, "defaultWorker") + "\n" +
    scope("__relay", relay, "defaultWorker, ChunkRelayHub") + "\n" +
    scope("__status", status, "defaultWorker, ChunkRelaySession") + "\n" +
    scope("__bootstrap", bootstrap, "handleWarpBootstrapRequest, isWarpBootstrapPath") + "\n" +
    entry.trimEnd() + "\n";
}

const files = ["worker.js","chunk-relay-worker.js","chunk-relay-status-worker.js","warp-bootstrap-standalone-worker.js","warp-bootstrap-worker.js"];
const sources = Object.fromEntries(await Promise.all(files.map(async (name) => [
  name, (await readFile(new URL(name, import.meta.url), "utf8")).replace(/\r\n/g, "\n"),
])));
const output = new URL("dashboard-worker.js", import.meta.url);
const bundle = buildBundle(sources);
if (process.argv.includes("--check")) {
  const actual = (await readFile(output, "utf8")).replace(/\r\n/g, "\n");
  if (actual !== bundle) throw new Error("dashboard-worker.js is stale; run node scripts/cloudflare-worker/build-dashboard-worker.mjs");
} else {
  await writeFile(output, bundle);
}
